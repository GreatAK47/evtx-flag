@dataclass(frozen=True)
class EidEntry:
    """One (event-id, channel) reference row in the dictionary."""

    eid: str
    channel: str
    name: str
    category: str
    tags: str


def _build_db() -> tuple[EidEntry, ...]:
    db: list[EidEntry] = []
    seen: set[tuple[str, str, str]] = set()
    for eid, channel, name, category, tags in _RAW:
        if not name:  # drop placeholder rows
            continue
        key = (eid, channel, name)
        if key in seen:  # e.g. "517" listed twice
            continue
        seen.add(key)
        db.append(EidEntry(eid, channel, name, category, tags))
    return tuple(db)


EID_DB: tuple[EidEntry, ...] = _build_db()

_SPLIT_RE = re.compile(r"[\s,，、;；]+")


def categories() -> list[str]:
    """Sorted unique category names (for the GUI filter combo box)."""
    return sorted({e.category for e in EID_DB})


def _match(e: EidEntry, terms: list[str], category: str) -> int:
    """Return a match score > 0 when the entry satisfies all terms.

    Score: 4 = every term equals the eid; 3 = some term equals the eid;
    2 = some term is an eid prefix/substring; 1 = plain text match.
    """
    if category and category != "全部" and e.category != category:
        return 0
    haystack = " ".join(
        (e.eid, e.channel, e.name, e.category, e.tags)
    ).lower()
    score = 1
    for term in terms:
        t = term.lower()
        if t == e.eid.lower():
            score = max(score, 3)
            continue
        if t in e.eid.lower():
            score = max(score, 2)
            continue
        if t not in haystack:
            return 0
    if terms and all(t.lower() == e.eid.lower() for t in terms):
        return 4
    return score


def search(
    keyword: str, category: str = "", limit: int = 400
) -> list[EidEntry]:
    """Fuzzy keyword search over the dictionary.

    * Pure-digit terms (``4720 4726``) mean "look up these IDs" - an OR
      of exact ID matches, which is what a user typing several IDs wants.
    * Mixed/word terms are AND-ed across eid/channel/name/category/tags
      (case-insensitive substring), i.e. fuzzy keyword lookup.
    """
    terms = [t for t in _SPLIT_RE.split(keyword.strip()) if t]
    if not terms:
        db = list(EID_DB)
        if category and category != "全部":
            return [e for e in db if e.category == category][:limit]
        return db[:limit]

    if all(t.isdigit() for t in terms):
        wanted = set(terms)
        db = [e for e in EID_DB if e.eid in wanted]
        if category and category != "全部":
            db = [e for e in db if e.category == category]
        return db[:limit]

    scored = [(_match(e, terms, category), i, e) for i, e in enumerate(EID_DB)]
    hits = [(s, i, e) for s, i, e in scored if s > 0]
    hits.sort(key=lambda x: (-x[0], x[1]))
    return [e for _, _, e in hits[:limit]]


def count() -> int:
    """Total number of reference rows."""
    return len(EID_DB)
